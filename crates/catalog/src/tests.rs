#[test]
fn schema_table_map_groups_and_sorts() {
    let snapshot = CatalogSnapshot {
        tables: vec![
            TableMeta {
                id: TableId("public.b".into()),
                name: "b".into(),
                schema: "public".into(),
                relation_kind: RelationKind::Table,
            },
            TableMeta {
                id: TableId("public.a".into()),
                name: "a".into(),
                schema: "public".into(),
                relation_kind: RelationKind::Table,
            },
            TableMeta {
                id: TableId("other.x".into()),
                name: "x".into(),
                schema: "other".into(),
                relation_kind: RelationKind::Table,
            },
        ],
        columns: Vec::new(),
        foreign_keys: Vec::new(),
    };

    let map = schema_table_map(&snapshot);
    assert_eq!(map.get("public"), Some(&vec!["a".into(), "b".into()]));
    assert_eq!(map.get("other"), Some(&vec!["x".into()]));
}
